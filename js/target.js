// 問題取得関数
// enemySpawner などから呼ぶ
// ===============================
export function getWord(options, minLen, maxLen){
    let tags;
    if (typeof options === 'object' && options !== null && !Array.isArray(options)) {
        ({ tags, minLen, maxLen } = options);
    } else {
        tags = options;
    }
    tags = tags || [];

    // 空文字やnullは「標準（タグなし）」のリクエストとして扱う
    const hasStandardRequest = tags.length === 0 || tags.some(t => !t || t === "");
    // 指定された有効なタグ（"長文"と空文字以外）を抽出
    const validSearchTags = tags.filter(t => t && t !== "" && t !== "長文");

    const isLongTextMode = tags.includes("長文");
    const poolSource = isLongTextMode ? TARGETS_LONG : TARGETS;

    let pool = poolSource.filter(target => {
        const len = target.text.length;
        const lenMatch =
            len >= minLen && len <= maxLen;

        // ターゲット側のタグ（空文字は除外）
        const targetTags = (target.tags || []).filter(t => t && t !== "");

        // 1. 標準リクエストがあり、ターゲットがタグなしの場合
        const standardMatch = hasStandardRequest && targetTags.length === 0;
        // 2. 指定されたタグのいずれかがターゲットに含まれる場合
        const specificMatch = validSearchTags.some(tag => targetTags.includes(tag));

        return lenMatch && (standardMatch || specificMatch);

    });

    if(pool.length === 0){
        console.warn("条件に合う問題がない", tags, minLen, maxLen);
        return null;
    }

    const target =
        pool[Math.floor(Math.random()*pool.length)];

    return target;
}